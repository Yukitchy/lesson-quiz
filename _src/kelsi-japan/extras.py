def tip_card(a, b, c, d):
    return (f'<details class="card tipcard"><summary><span class="head"><span class="name">{bi(a, c)}</span></span>'
            f'<span class="chev" aria-hidden="true"></span></summary><div class="body"><p class="why">{bi(b, d)}</p></div></details>')


def phrase_card(j, r, m, n):
    note = f'<p class="note">{e(n)}</p>' if n else ""
    return f'<div class="phrase"><p class="jp" lang="ja">{e(j)}</p><p class="ro">{e(r)}</p><p class="mean">{e(m)}</p>{note}</div>'


def tour_card(t, h, loc, im, u, de, dj, me):
    who = bi(("With your teacher" if me else "Guide friend") + " · " + h, ("ユウキ本人" if me else "ガイド仲間") + "・" + h)
    cls = "tourcard me" if me else "tourcard"
    return (f'<a class="{cls}" href="{e(u)}" target="_blank" rel="noopener"><img src="tours/{im}" alt="{e(h)}" loading="lazy">'
            f'<div class="tb"><p class="cat">{who}</p><h3>{e(t)}</h3><p class="loc">{e(loc)}</p><p>{bi(de, dj)}</p>'
            f'<span class="go">{bi("See the tour", "ツアーを見る")}</span></div></a>')


def section(id_, h_en, h_ja, lead_en, lead_ja, inner_cls, inner):
    return (f'<section class="city extra" id="{id_}"><header><h2>{bi(h_en, h_ja)}</h2></header>'
            f'<p class="lead">{bi(lead_en, lead_ja)}</p><div class="{inner_cls}">{inner}</div></section>')


